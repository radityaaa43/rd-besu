#!/usr/bin/env bash
# Regenerates opa/test/fabricx/pki.rego: throw-away test PKI for the Fabric-X caller-identity rules (bi.platform.fabricx).
# Public certificates only: every private key lives in a mktemp dir that is deleted on exit, so nothing here can sign anything real.
# Validity 100 years from now (OPA verifies at the real clock); ECDSA P-256. usage: ./gen-pki.sh > pki.rego
set -euo pipefail
d="$(mktemp -d)"; trap 'rm -rf "$d"' EXIT
cd "$d"

ca() {  # ca <name> <CN>: self-signed CA, pathlen 0 (like bank-gw-ca-<N> and the Fabric-X org TLS roots)
  openssl ecparam -name prime256v1 -genkey -noout -out "$1.key"
  openssl req -x509 -new -key "$1.key" -sha256 -days 36500 -subj "/CN=$2" \
    -addext "basicConstraints=critical,CA:TRUE,pathlen:0" -addext "keyUsage=critical,keyCertSign,cRLSign" -out "$1.pem"
}
leaf() {  # leaf <name> <CN> <ca> <eku>: end-entity cert signed directly by <ca>
  openssl ecparam -name prime256v1 -genkey -noout -out "$1.key"
  openssl req -new -key "$1.key" -subj "/CN=$2" -out "$1.csr"
  printf 'basicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=%s\nsubjectAltName=DNS:%s\n' "$4" "$2" > "$1.ext"
  openssl x509 -req -in "$1.csr" -CA "$3.pem" -CAkey "$3.key" -CAcreateserial -days 36500 -sha256 -extfile "$1.ext" -out "$1.pem" 2>/dev/null
}
emit() { printf '%s := `%s`\n\n' "$1" "$(cat "$2.pem")"; }

for n in 1 2 3 4; do ca "gw$n" "fca-org$n"; ca "lensa$n" "bank-gw mTLS CA $n"; done
for n in 1 2 3 4; do leaf "lensa_leaf$n" lensa "lensa$n" clientAuth; done
leaf peer_1_org1 fx-gw-1-peer gw1 clientAuth       # right CN, right org root
leaf peer_2_org2 fx-gw-2-peer gw2 clientAuth
leaf peer_3_org3 fx-gw-3-peer gw3 clientAuth
leaf peer_1_org3 fx-gw-1-peer gw3 clientAuth       # CN of org 1 signed by org 3's root
leaf peer_1_lensa fx-gw-1-peer lensa1 clientAuth   # CN of org 1 signed by a Lensa CA
leaf peer_server_cn fx-gw-1 gw1 clientAuth         # the gateway SERVER cert CN, not the peer client CN
leaf peer_server_eku fx-gw-1-peer gw1 serverAuth   # peer CN but server-only key usage
leaf lensa_by_gw lensa gw1 clientAuth              # CN lensa signed by an org root

{
  echo '# GENERATED by gen-pki.sh (public test certificates, no private keys); do not edit.'
  echo '# Fabric-X caller identity fixtures: gw<N> = org N TLS root, lensa<N> = bank-gw-ca-<N> of node N.'
  echo 'package fabricx_pki'
  echo
  for n in 1 2 3 4; do emit "ca_gw$n" "gw$n"; emit "ca_lensa$n" "lensa$n"; emit "lensa_leaf$n" "lensa_leaf$n"; done
  for l in peer_1_org1 peer_2_org2 peer_3_org3 peer_1_org3 peer_1_lensa peer_server_cn peer_server_eku lensa_by_gw; do emit "$l" "$l"; done
} | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}'  # no trailing blank line (opa fmt clean)
