#!/usr/bin/env bash
# Regenerates opa/test/iroha3/pki.rego: throw-away test PKI for the iroha3 gateway rules (bi.platform.iroha3).
# Public certificates only: every private key lives in a mktemp dir that is deleted on exit, so nothing here can sign anything real.
# Validity 100 years from now (OPA verifies at the real clock); ECDSA P-256. usage: ./gen-pki.sh > pki.rego
set -euo pipefail
d="$(mktemp -d)"; trap 'rm -rf "$d"' EXIT
cd "$d"

ca() {  # ca <name> <CN>: self-signed CA, pathlen 0
  openssl ecparam -name prime256v1 -genkey -noout -out "$1.key"
  openssl req -x509 -new -key "$1.key" -sha256 -days 36500 -subj "/CN=$2" \
    -addext "basicConstraints=critical,CA:TRUE,pathlen:0" -addext "keyUsage=critical,keyCertSign,cRLSign" -out "$1.pem"
}
leaf() {  # leaf <name> <CN> <ca> <eku>: end-entity cert signed directly by <ca>
  openssl ecparam -name prime256v1 -genkey -noout -out "$1.key"
  openssl req -new -key "$1.key" -subj "/CN=$2" -out "$1.csr"
  printf 'basicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=%s\nsubjectAltName=DNS:%s\n' "$4" "$2" > "$1.ext"
  openssl x509 -req -in "$1.csr" -CA "$3.pem" -CAkey "$3.key" -CAcreateserial -days 36500 -sha256 -extfile "$1.ext" -out "$1.pem" 2>/dev/null
}
emit() { printf '%s := `%s`\n\n' "$1" "$(cat "$2.pem")"; }

nodes="bi bank_a bank_b bank_c"
for n in $nodes; do ca "lensa_ca_$n" "iroha3 lensa CA $n"; ca "role_ca_$n" "iroha3 role CA $n"; done
for n in $nodes; do
  leaf "lensa_leaf_$n" lensa "lensa_ca_$n" clientAuth     # Lensa of party <n>: CN lensa, party's Lensa CA
  leaf "role_leaf_$n" "${n//_/-}" "role_ca_$n" clientAuth  # one leaf per role: CN = role (bank-a ...), the role's own CA
done
leaf bank_a_by_b bank-a role_ca_bank_b clientAuth          # CN bank-a signed by bank-b's CA
leaf lensa_by_role lensa role_ca_bank_a clientAuth         # CN lensa signed by a role CA
leaf bi_by_lensa bi lensa_ca_bi clientAuth                 # CN bi signed by a Lensa CA
leaf server_eku bank-a role_ca_bank_a serverAuth           # right CN and CA, server-only key usage
leaf bank_d bank-d role_ca_bank_a clientAuth               # unknown role CN

{
  echo '# GENERATED by gen-pki.sh (public test certificates, no private keys); do not edit.'
  echo '# iroha3 caller identity fixtures: lensa_ca_<node> = Lensa client CA of that gateway, role_ca_<role> = the role CA (node and role: bi, bank_a, bank_b, bank_c).'
  echo 'package iroha3_pki'
  echo
  for n in $nodes; do emit "lensa_ca_$n" "lensa_ca_$n"; emit "role_ca_$n" "role_ca_$n"; emit "lensa_leaf_$n" "lensa_leaf_$n"; emit "role_leaf_$n" "role_leaf_$n"; done
  for l in bank_a_by_b lensa_by_role bi_by_lensa server_eku bank_d; do emit "$l" "$l"; done
} | sed -e :a -e '/^\n*$/{$d;N;ba' -e '}'  # no trailing blank line (opa fmt clean)
