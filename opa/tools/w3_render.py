#!/usr/bin/env python3 -I
"""OPA config of the iroha3 gateway per party (W3, S14.D). Python stdlib only; PUBLIC keys only (opa/w3/public-keys.yaml = the live bank-gw-opa-v2 `keys:` block).
  w3_render.py <out dir>   writes opa-<party>.yaml (bi, bank-a, bank-b, bank-c) and SHA256SUMS; the same input gives the same bytes.
The consumer (iroha render) overrides services.bundle-server.url, decision_logs and status and adds the --set flags named in the header of each file."""
import hashlib, os, re, sys
PARTIES = ("bi", "bank-a", "bank-b", "bank-c")
KEYS = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "w3", "public-keys.yaml")
T = '''# OPA config for the iroha3 gateway of party {P} (W3, S14.D). PUBLIC: no secret, no token, no private key. Generated by besu from the live bank-gw-opa-v2 `keys:` block
# (sha256 of that live file ba27d313675ec38b...). The consumer (iroha render) overrides services.bundle-server.url, decision_logs and status with console output and adds
# --set=bundles.bi.resource=bi/latest.tar.gz --set=bundles.bank.resource=bank/latest.tar.gz --set=labels.gateway=gateway-{P}.
plugins:
  envoy_ext_authz_grpc:
    addr: 127.0.0.1:9191
    path: gw/allow
    dry-run: false
services:
  bundle-server:
    url: http://bundle-server.rd-zeto-{P}.svc.cluster.local
# A bundle only activates when its signature verifies with the key named here; a bad one keeps the old bundle. The `bi` bundle is signed by BI's key, the party's own `bank` bundle by its own key.
bundles:
  bi:
    service: bundle-server
    polling: {{min_delay_seconds: 5, max_delay_seconds: 15}}
    signing: {{keyid: bi}}
  bank:
    service: bundle-server
    polling: {{min_delay_seconds: 5, max_delay_seconds: 15}}
    signing: {{keyid: {K}}}
decision_logs:
  console: true
status:
  console: true
'''

def render(party, keys):
    if party not in PARTIES: raise ValueError(f"unknown party {party}")
    if "PRIVATE KEY" in keys or not keys.startswith("keys:"): raise ValueError("keys must be the public `keys:` block, no private key material")
    if re.findall(r"^  ([a-z0-9-]+):\n    algorithm: RS256", keys, re.M) != list(PARTIES): raise ValueError("keys block must hold exactly bi, bank-a, bank-b, bank-c (RS256)")
    return T.format(P=party, K=party) + keys

if __name__ == "__main__":
    if len(sys.argv) != 2: sys.exit(__doc__)
    keys = open(KEYS, encoding="utf-8").read(); os.makedirs(sys.argv[1], exist_ok=True); sums = []
    for p in PARTIES:
        b = render(p, keys)
        with open(os.path.join(sys.argv[1], f"opa-{p}.yaml"), "w", encoding="utf-8", newline="") as f: f.write(b)
        sums.append(f"{hashlib.sha256(b.encode()).hexdigest()}  opa-{p}.yaml")
    with open(os.path.join(sys.argv[1], "SHA256SUMS"), "w") as f: f.write("\n".join(sums) + "\n")
    print("\n".join(s[:12] + " " + s[66:] for s in sums))
